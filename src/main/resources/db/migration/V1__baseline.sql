    ip_address character varying(255),
    issued_at timestamp(6) with time zone,
    user_agent character varying(255),
    user_id integer
);

ALTER TABLE public.refresh_token ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.refresh_token_id_seq START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1
);

CREATE TABLE public.task (
    id integer NOT NULL,
    created timestamp(6) without time zone,
    description text,
    due_date timestamp(6) without time zone,
    priority integer,
    status character varying(255),
    title character varying(255),
    user_id integer,
    edited timestamp(6) without time zone,
    "position" integer NOT NULL,
    board_column_id integer NOT NULL
);

CREATE TABLE public.task_event (
    id integer NOT NULL,
    at timestamp(6) without time zone NOT NULL,
