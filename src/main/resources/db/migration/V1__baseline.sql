-- The schema as it was on production when Flyway was introduced (pg_dump --schema-only, PostgreSQL 15),
-- until then created by Hibernate's ddl-auto=update.
-- On production this migration is not run: baseline-on-migrate marks it as applied.
-- On an empty database (local, CI, tests) it creates the schema.
-- Leftovers from earlier versions are kept on purpose so this matches production exactly:
-- task.priority, task.status, refresh_token.expiry_date, refresh_token.user_email.

CREATE TABLE public.board (
    id integer NOT NULL,
    name character varying(255) NOT NULL,
    user_id integer NOT NULL,
    slug character varying(60)
);

CREATE TABLE public.board_column (
    id integer NOT NULL,
    color character varying(7),
    name character varying(255) NOT NULL,
    "position" integer NOT NULL,
    board_id integer NOT NULL
);

