-- Notes on a task: plain text, editable and deletable by the owner. Not shown on shared boards.
-- Deleting a task deletes its notes (ON DELETE CASCADE), whichever way the task is deleted.
CREATE TABLE task_note (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id integer NOT NULL REFERENCES task (id) ON DELETE CASCADE,
    user_id integer REFERENCES "user" (id),
    text text NOT NULL,
    created timestamp(6) without time zone NOT NULL,
    edited timestamp(6) without time zone
);

CREATE INDEX task_note_task_id ON task_note (task_id);
